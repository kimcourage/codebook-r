testthat::test_that("progressive disclosure follows loaded sources without approving work", {
  f <- server_fixture()
  shiny::testServer(f$server, {
    session$flushReact()
    testthat::expect_equal(output$ui_ready, "no")
    testthat::expect_equal(output$ui_has_result, "no")
    session$setInputs(data_file = f$data_a)
    testthat::expect_equal(output$ui_has_data, "yes")
    testthat::expect_equal(output$ui_has_books, "no")
    testthat::expect_equal(output$ui_ready, "no")
    session$setInputs(book_files = f$book_a)
    testthat::expect_equal(output$ui_ready, "yes")
    testthat::expect_equal(output$ui_has_rules, "yes")
    testthat::expect_equal(output$ui_has_selection, "no")
    testthat::expect_length(approved_keys(), 0)
    testthat::expect_equal(f$calls$n, 0L)
    session$setInputs(data_file = NULL)
    testthat::expect_equal(output$ui_ready, "no")
    testthat::expect_equal(output$ui_has_data, "no")
  })
})

testthat::test_that("result visibility respects stale results and preserves the basic download", {
  f <- server_fixture()
  shiny::testServer(f$server, {
    load_fixture(session, f)
    session$setInputs(approved_rules = rule_keys(), run_button = 1L)
    testthat::expect_equal(output$ui_has_result, "yes")
    testthat::expect_equal(output$ui_has_base, "yes")
    session$setInputs(start_additional = 1L)
    testthat::expect_equal(output$ui_has_result, "no")
    testthat::expect_equal(output$ui_has_base, "yes")
    testthat::expect_equal(output$ui_has_rules, "no")
    testthat::expect_match(output$ui_selection_summary, "0.*0")
    session$setInputs(data_file = f$data_b)
    testthat::expect_equal(output$ui_has_result, "no")
    testthat::expect_equal(output$ui_has_base, "no")
  })
})

testthat::test_that("no-change output and changed selections update the presented result state", {
  f <- server_fixture()
  shiny::testServer(f$server, {
    load_fixture(session, f)
    session$setInputs(approved_rules = character(), run_unchanged = 1L)
    testthat::expect_equal(output$ui_has_result, "yes")
    testthat::expect_equal(current_result()$applied$data, dataset())
    session$setInputs(approved_rules = rule_keys())
    testthat::expect_equal(output$ui_has_selection, "yes")
    testthat::expect_equal(output$ui_has_result, "no")
    testthat::expect_equal(output$ui_has_base, "yes")
    testthat::expect_null(current_result())
  })
})
